#!/usr/bin/env python3
"""
build-fo-projects-field.py — regenerate the field portal's bundled project snapshot.

Reads:   platform/data/fo-projects-field.js  (source of truth — field-safe list)
Writes:  field/functions/lib/fo-projects-data.js  (bundled snapshot for Workers)

Then calls geocode-job-coords.py to refresh job-coords.js so the weather tile
has coords for any newly added projects.

Run from the repo root whenever fo-projects-field.js changes (new awarded jobs,
scope updates):

    python3 platform/scripts/build-fo-projects-field.py

After this script completes:
    1. Commit the updated fo-projects-data.js and job-coords.js on the working branch.
    2. Redeploy pf-field (see field/README.md for the deploy command).

Design goals:
  - Zero financials, GC, contract values in the output.
  - Keep address and city_state fields (needed by /api/weather geocoder).
  - Preserve the existing fo-projects-data.js address annotations (addresses
    are added there manually when actual site addresses are confirmed).
"""

import re, os, sys, subprocess, json

REPO_ROOT   = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
SOURCE_JS   = os.path.join(REPO_ROOT, "platform", "data", "fo-projects-field.js")
OUT_JS      = os.path.join(REPO_ROOT, "field", "functions", "lib", "fo-projects-data.js")
GEOCODE_PY  = os.path.join(REPO_ROOT, "field", "scripts", "geocode-job-coords.py")


def parse_fo_projects_field(path):
    """
    Parse window.PF_FO_PROJECTS.projects from the JS file.
    Returns list of dicts with keys: number, name, city_state, discipline, record.
    """
    text = open(path).read()
    # Extract the JSON array from the "projects": [...] section
    m = re.search(r'"projects"\s*:\s*(\[.*?\])', text, re.DOTALL)
    if not m:
        raise ValueError(f"Could not find projects array in {path}")
    return json.loads(m.group(1))


def load_existing_addresses(path):
    """
    Extract the existing address annotations from fo-projects-data.js so we
    don't lose manually-added addresses on each regeneration.
    Returns dict: {number: address_or_null}
    """
    if not os.path.exists(path):
        return {}
    text = open(path).read()
    # Parse JS object literals: { number: '...', ..., address: '...' }
    entries = {}
    # Match each entry block
    for block in re.findall(r'\{[^}]+\}', text, re.DOTALL):
        num_m   = re.search(r"number\s*:\s*'([^']+)'", block)
        addr_m  = re.search(r"address\s*:\s*'([^']*)'", block)
        null_m  = re.search(r"address\s*:\s*null", block)
        if num_m:
            num = num_m.group(1)
            if addr_m:
                entries[num] = addr_m.group(1)
            elif null_m:
                entries[num] = None
    return entries


def main():
    print(f"Reading source: {SOURCE_JS}")
    projects = parse_fo_projects_field(SOURCE_JS)
    print(f"  {len(projects)} projects found")

    print(f"Loading existing address annotations from: {OUT_JS}")
    existing_addrs = load_existing_addresses(OUT_JS)
    print(f"  {len(existing_addrs)} existing entries (addresses preserved)")

    # Build the output entries.
    # Fields kept: number, name, city_state, address
    # city_state comes from the source file; address preserved from existing output
    # (updated manually or by geocode-job-coords.py knowledge).
    rows = []
    for p in projects:
        num        = p["number"]
        name       = p["name"]
        city_state = p.get("city_state", "")
        address    = existing_addrs.get(num, None)  # preserve existing annotation
        rows.append((num, name, city_state, address))

    # Render the JS file
    lines = [
        "// Field-safe project list bundled into the Functions at deploy time.",
        "// Source: platform/data/fo-projects-field.js (same data, stripped to {number,name,city_state,address}).",
        "// ZERO financials, ZERO GC data, ZERO contract values.",
        "//",
        "// AUTO-GENERATED by platform/scripts/build-fo-projects-field.py",
        "// DO NOT EDIT BY HAND — run that script instead.",
        "//",
        "// `address` is used by /api/weather for the NWS forecast.",
        "// null → weather tile shows 'No site location on file for this job.'",
        "// Addresses are populated by geocode-job-coords.py and preserved on",
        "// regeneration.  Update geocode-job-coords.py JOB_DATA when adding new jobs.",
        "",
        "export const FO_PROJECTS = [",
    ]

    for num, name, city_state, address in rows:
        addr_val = f"'{address}'" if address is not None else "null"
        # Pad for readability
        lines.append(
            f"  {{ number: {json.dumps(num)},  name: {json.dumps(name)},  "
            f"city_state: {json.dumps(city_state)},  address: {addr_val} }},"
        )

    lines += ["];", ""]
    content = "\n".join(lines)

    with open(OUT_JS, "w") as f:
        f.write(content)
    print(f"Wrote {OUT_JS}")

    # Run geocode script to refresh job-coords.js
    print()
    print("Running geocode-job-coords.py to refresh job-coords.js...")
    print("  (skips already-geocoded jobs; only calls Nominatim for new/missing entries)")
    print()
    result = subprocess.run(
        [sys.executable, GEOCODE_PY],
        cwd=REPO_ROOT,
    )
    if result.returncode != 0:
        print(f"\nWARNING: geocode-job-coords.py exited {result.returncode}", file=sys.stderr)
        sys.exit(result.returncode)

    print()
    print("Done. Next steps:")
    print("  git add field/functions/lib/fo-projects-data.js field/functions/lib/job-coords.js platform/data/fo-projects-field.js")
    print("  git commit -m 'chore: regenerate field portal project data'")
    print("  Then redeploy pf-field (see field/README.md)")


if __name__ == "__main__":
    main()
