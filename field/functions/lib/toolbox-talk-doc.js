// toolbox-talk-doc.js: PDF renderer + email + SharePoint upload for Toolbox Talks.
//
// ZERO FINANCIALS: this renderer never touches dollar amounts, rates, or costs.
// Safety meeting records only.

import { PdfDoc, bytesToBase64, PF } from './pdf.js';
import { TOPIC_LABELS } from './toolbox-talk-store.js';
import { GRAPH } from './graph.js';

export const MAIL_FROM = 'peter@pierfoundations.com';

// SP folder path for Toolbox Talk PDFs.
// Coordinator-proposed path: "05 - Field Operations/Toolbox Talks/"
// Rationale: TT records are safety-meeting logs, not project deliverables.
// Grouping under Field Operations / Toolbox Talks makes them easy to audit
// by safety coordinators without navigating individual project folders.
// Year subfolders (YYYY) keep the listing manageable over time.
const TT_SP_BASE_PATH = '05 - Field Operations/Toolbox Talks';

// Convert YYYY-MM-DD -> MM/DD/YYYY for display.
function fmtDate(s) {
  if (!s) return '';
  const m = String(s).match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (!m) return String(s);
  return `${m[2]}/${m[3]}/${m[1]}`;
}

// ---------------------------------------------------------------------------
// 1) RENDER: record -> PDF bytes
// ---------------------------------------------------------------------------
export function renderToolboxTalkPdf(rec) {
  const doc = new PdfDoc();

  const topicLabel = TOPIC_LABELS[rec.topic] || rec.topic || '-';
  const topicDisplay = (rec.topic === 'other' && rec.topicOther)
    ? `Other: ${rec.topicOther}`
    : topicLabel;

  doc.brandHeader('Toolbox Talk', [
    { label: 'Project',    value: rec.projectName || '-' },
    { label: 'Date',       value: fmtDate(rec.date) || '-' },
    { label: 'Time',       value: rec.time || '-' },
    { label: 'Presenter',  value: rec.presenter || '-' },
    { label: 'Project No', value: rec.projectId || '-' },
  ]);
  doc.spacer(2);

  // ---- Meeting Details ----
  // Presenter is already in the header; omit it here to avoid repetition.
  doc.heading('Meeting Details');
  doc.table([
    { label: 'Location', value: rec.location || '-' },
    { label: 'Topic',    value: topicDisplay },
  ], { valueW: 280 });

  // ---- Key Points Discussed ----
  doc.heading('Key Points Discussed');
  doc.text(rec.keyPoints && rec.keyPoints.trim() ? rec.keyPoints : 'None recorded.', { size: 10 });

  // ---- Site-Specific Hazards ----
  doc.heading('Hazards Specific to Today\'s Work');
  doc.text(rec.hazards && rec.hazards.trim() ? rec.hazards : 'None identified.', { size: 10 });

  // ---- Questions or Concerns Raised ----
  doc.heading('Questions or Concerns Raised');
  doc.text(rec.questions && rec.questions.trim() ? rec.questions : 'None.', { size: 10 });

  // ---- Corrective Actions ----
  const actions = rec.actions && rec.actions.trim();
  if (actions) {
    doc.heading('Corrective Actions');
    doc.text(actions, { size: 10 });
  }

  // ---- Attendees (attendance-only; acknowledged removed R6 per Derek 2026-10-30) ----
  // Old records may have acknowledged flags in stored data; they are intentionally
  // omitted from the PDF for all records (new and re-rendered old).
  const attendees = Array.isArray(rec.attendees) ? rec.attendees.filter((a) => a && a.name) : [];
  doc.heading('Attendees');
  if (attendees.length) {
    doc.table(attendees.map((a, i) => ({
      label: `${i + 1}. ${a.name}`,
      value: '',
    })));
  } else {
    doc.text('No attendees recorded.', { size: 10 });
  }

  // ---- Footer ----
  // No spacer before rule: keeps the footer on the last content page rather than
  // forcing a new page just for the footer when content fits on one page.
  doc.rule(0.8, PF.border);
  const gen = new Date().toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
  doc.text(`Generated by the PF Platform on submit - ${gen}. Safety meeting record.`,
    { size: 8, color: PF.muted });

  return doc.toBytes();
}

// ---- Filename convention: "YY-MMDD-<Project>-Toolbox Talk.pdf" ----
function safeProjectName(v, fallback) {
  let s = String(v == null ? '' : v)
    .replace(/[\\/:*?"<>|]/g, '').replace(/[\x00-\x1f]/g, '')
    .replace(/\s+/g, ' ').trim()
    .replace(/^\.+/, '').replace(/\.+$/, '').trim()
    .slice(0, 80).trim();
  return s || (fallback || 'Project');
}

export function pdfFilename(rec) {
  const iso = /^\d{4}-\d{2}-\d{2}/.test(String(rec.date || ''))
    ? String(rec.date).slice(0, 10)
    : new Date().toISOString().slice(0, 10);
  const [yyyy, mm, dd] = iso.split('-');
  const datePart = `${yyyy.slice(2)}-${mm}${dd}`;
  const name = safeProjectName(rec.projectName || rec.projectId, 'Project');
  return `${datePart}-${name}-Toolbox Talk.pdf`;
}

